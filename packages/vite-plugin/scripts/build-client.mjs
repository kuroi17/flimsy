import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(__dirname, '..');
const entry = path.join(pkgRoot, 'src/client/studio.ts');
const outFile = path.join(pkgRoot, 'src/client-script.generated.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: false,
  charset: 'utf8',
});

const bundledJs = result.outputFiles[0].text;
const generatedTs = `// AUTO-GENERATED by scripts/build-client.mjs from src/client/*.ts — do not edit directly.\nexport const clientScript: string = ${JSON.stringify(bundledJs)};\n`;

await fs.writeFile(outFile, generatedTs, 'utf-8');
console.log(`Bundled Flimsy browser studio (${bundledJs.length} bytes) -> src/client-script.generated.ts`);
